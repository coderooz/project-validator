import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { existsSync, mkdirSync } from 'node:fs';
import type { ValidationReport, ReporterModule } from '../types.js';

function generateMarkdown(report: ValidationReport): string {
  const lines: string[] = [];

  lines.push(`# Validation Report: ${report.project.name}`);
  lines.push('');
  lines.push(`- **Framework**: ${report.project.framework.type}`);
  lines.push(`- **Files**: ${report.project.files.length}`);
  lines.push(`- **Duration**: ${report.duration}ms`);
  lines.push(`- **Timestamp**: ${report.timestamp}`);
  lines.push('');

  lines.push('## Summary');
  lines.push('');
  lines.push(`| Metric | Value |`);
  lines.push(`|--------|-------|`);
  lines.push(`| Total Checks | ${report.summary.total} |`);
  lines.push(`| Passed | ${report.summary.passed} |`);
  lines.push(`| Failed | ${report.summary.failed} |`);
  lines.push(`| Total Issues | ${report.summary.issues} |`);
  lines.push(`| Critical | ${report.summary.critical} |`);
  lines.push(`| High | ${report.summary.high} |`);
  lines.push(`| Medium | ${report.summary.medium} |`);
  lines.push(`| Low | ${report.summary.low} |`);
  lines.push(`| Info | ${report.summary.info} |`);
  lines.push('');

  lines.push('## Health Score');
  lines.push('');
  lines.push(`**Overall: ${report.healthScore.overall}/100**`);
  lines.push('');
  lines.push('| Category | Score |');
  lines.push('|----------|-------|');
  for (const b of report.healthScore.breakdown) {
    lines.push(`| ${b.category} | ${b.score}/100 |`);
  }
  lines.push('');

  const phaseOrder = ['static', 'environment', 'architecture', 'compile', 'runtime', 'security'];
  for (const phase of phaseOrder) {
    const phaseResults = report.results.filter((r) => r.phase === phase);
    if (phaseResults.length === 0) continue;

    lines.push(`## ${phase.charAt(0).toUpperCase() + phase.slice(1)} Phase`);
    lines.push('');

    for (const result of phaseResults) {
      const status = result.passed ? '✅ Passed' : '❌ Failed';
      lines.push(`### ${result.name} — ${status}`);
      lines.push('');
      if (result.issues.length > 0) {
        lines.push('| Severity | File | Line | Message |');
        lines.push('|----------|------|------|---------|');
        for (const issue of result.issues) {
          const file = issue.file ?? '-';
          const line = issue.line ? String(issue.line) : '-';
          lines.push(`| ${issue.severity} | ${file} | ${line} | ${issue.message} |`);
        }
        lines.push('');
      }
    }
  }

  lines.push('---');
  lines.push(`_Generated by Project Validator at ${report.timestamp}_`);
  lines.push('');

  return lines.join('\n');
}

export function createMarkdownReporter(outputPath?: string): ReporterModule {
  return {
    name: 'markdown',
    async write(report: ValidationReport): Promise<void> {
      const markdown = generateMarkdown(report);
      const filePath = outputPath ?? join(process.cwd(), 'reports', 'validation-report.md');

      const dir = dirname(filePath);
      if (!existsSync(dir)) {
        mkdirSync(dir, { recursive: true });
      }

      writeFileSync(filePath, markdown, 'utf-8');
      console.log(`📄 Markdown report written to: ${filePath}`);
    },
  };
}
